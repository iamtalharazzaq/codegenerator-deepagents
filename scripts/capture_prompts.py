"""Regenerates docs/PROMPTS-AS-SENT.md: runs the team with a recording model and writes down exactly what the model is
sent (system prompts, first messages, tool descriptions, our injected messages). Run it from the repo root:
`make prompts`. Re-run it after editing any prompt.md, config.yaml, TEAM_RULES or tool docstring."""
import asyncio
import sys
import tempfile

sys.path.insert(0, "tests")
from pathlib import Path

import test_team as T
from langchain_core.language_models.fake_chat_models import GenericFakeChatModel
from langchain_core.messages import AIMessage, SystemMessage

from orchestrator.config import RunConfig

CAPTURED = []   # (who, system text, [messages], [tools])
BOUND = []

class Rec(GenericFakeChatModel):
    def bind_tools(self, tools, **kw):
        BOUND.append([(getattr(t, "name", None) or t.get("name"), getattr(t, "description", None) or t.get("description", "")) for t in tools])
        return self
    async def _agenerate(self, messages, stop=None, run_manager=None, **kw):
        system = next((m.content for m in messages if isinstance(m, SystemMessage)), "")
        if isinstance(system, list):
            system = "\n\n[next block]\n\n".join(b.get("text", "") if isinstance(b, dict) else str(b) for b in system)
        who = "PM" if "You are the Project Manager" in str(system) else "SPECIALIST"
        if not any(c[0] == who for c in CAPTURED):
            CAPTURED.append((who, str(system), [(type(m).__name__, str(m.content)) for m in messages if not isinstance(m, SystemMessage)], BOUND[-1] if BOUND else []))
        return await super()._agenerate(messages, stop, run_manager, **kw)

async def main():
    script = [
        T.delegate("backend-developer", "Create greet.py with greet(name) returning 'Hello, <name>!'. Done when the file exists.\nWRITES: greet.py"),
        T.calls(T.tc("write_file", {"file_path": "/greet.py", "content": "x"})),
        AIMessage(content=T.PASS),
        AIMessage(content="Done.\n---\nstatus: pass\nreason: ok\n---"),
    ]
    await T.run(Path(tempfile.mkdtemp()), script, model=Rec(messages=iter(script)), cfg=RunConfig(max_nudges=0))
asyncio.run(main())

from orchestrator.roles import ALL_ROLES, load_role
from orchestrator.team import NUDGE, TEAM_RULES

out = ["# What the model is sent (captured from a real run of the team code)\n",
       "Generated by running the team with a recording model. Three kinds of text reach the model:\n",
       "1. **Ours, in files you can edit:** `orchestrator/agents/<role>/prompt.md` (system prompt), `config.yaml` (the `description` the Project Manager sees for each specialist), `TEAM_RULES` and `NUDGE` in `orchestrator/team.py`, tool docstrings in `orchestrator/sandbox_tools.py`.",
       "2. **Ours, built in code at run time:** the first user message and the refusal messages (listed at the end).",
       "3. **deepagents' own text**, added around ours (tool descriptions, its base prompt). Shown here so nothing is hidden; edit it only by overriding in `create_deep_agent`.\n"]
for who, system, msgs, tools in CAPTURED:
    title = "PROJECT MANAGER (main agent)" if who == "PM" else "SPECIALIST (example: backend-developer)"
    out.append(f"\n---\n\n## {title}\n\n### System prompt, exactly as sent ({len(system)} characters)\n\n~~~text\n{system}\n~~~\n")
    out.append("### Messages after the system prompt\n")
    for kind, text in msgs:
        out.append(f"**{kind}:**\n\n~~~text\n{text}\n~~~\n")
    out.append("### Tools the model can call (name: description)\n")
    for name, desc in tools:
        out.append(f"- **{name}**: {desc.strip()[:1800]}{'…' if len(desc.strip())>1800 else ''}\n")
out.append("\n---\n\n## Messages our code writes to the model\n")
out.append("- **Resume note** (first message of a resumed run, built by `resume_note` in `orchestrator/runner.py`): \"This run was stopped earlier. … Work so far (do not redo what passed): … Guidance from the person: … Carry on from here: fix or redo only what is needed, then finish with the final status block.\"")
out.append(f"- **Nudge** (when the Project Manager ends without delegating):\n\n~~~text\n{NUDGE}\n~~~")
out.append("- **Unknown specialist:** `Unknown sub-agent '<name>'. Use one of: <the ten names>.`")
out.append("- **Delegation limit:** `Delegation limit reached. Delegate nothing more: end now with a short summary and a final status block (status: fail unless every needed task already passed).`")
out.append("- **Plan rejected:** `The person rejected the plan. Delegate nothing: end with status: fail, reason: plan rejected.`")
out.append("- **A specialist failed hard** (timeout, stuck, crash): `FAILED: the specialist <reason>`")
out.append("- **Blocked tool call** (to a specialist): `Blocked: <reason>. Do not retry this path; write only inside your task's scope.`")
out.append("\n## Specialist roster the Project Manager sees (config.yaml `description`)\n")
for r in ALL_ROLES:
    c = load_role(r); out.append(f"- **{c.name}** (tools: {', '.join(c.tools)}): {c.description}")
out.append("\n## Every specialist's own system prompt (prompt.md, then TEAM_RULES is appended)\n")
for r in ALL_ROLES:
    if r == "project_manager": continue
    out.append(f"### {r}\n\n~~~text\n{load_role(r).prompt}\n~~~\n")
out.append(f"### TEAM_RULES (appended to every specialist)\n\n~~~text\n{TEAM_RULES}\n~~~\n")
Path("docs/PROMPTS-AS-SENT.md").write_text("\n".join(out))
print("PM system chars:", len(CAPTURED[0][1]), "| specialist system chars:", len(CAPTURED[1][1]) if len(CAPTURED)>1 else None)
print("PM tools:", [n for n,_ in CAPTURED[0][3]]); print("specialist tools:", [n for n,_ in CAPTURED[1][3]] if len(CAPTURED)>1 else None)
